/** 拿名字；未知号返回 `ins_<n>`（与 thanm 对未知指令的写法一致）。 */
export function opcodeName(op) {
  return OPCODES[op]?.[0] ?? `ins_${op}`;
}
export function opcodeGroup(op) {
  return OPCODES[op]?.[1] ?? '?';
}
