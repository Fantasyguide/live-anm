/** 参数角色数组；未知 opcode 返回 null（调用方自己决定怎么办，别猜）。 */
export function signatureOf(op) {
  const s = SIGNATURES[op];
  return s === undefined ? null : [...s];
}

/** 只有 `f` 是浮点，其余角色都占整型位置。 */
export function isFloatRole(role) {
  return role === 'f';
}
